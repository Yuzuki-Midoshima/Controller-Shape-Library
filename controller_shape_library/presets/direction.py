GLYPH_SIZE = .42
GLYPH_ADVANCE = .56


def _word_width(word):
    return GLYPH_SIZE + max(0, len(word) - 1) * GLYPH_ADVANCE


def _word_curves(word, start_x):
    curves = []
    for index, letter in enumerate(word):
        x_offset = start_x + index * GLYPH_ADVANCE
        for contour in OUTLINE_GLYPHS[letter]:
            curves.append({"degree": 1, "points": [
                (x_offset + x * GLYPH_SIZE, 0.0, (y - .5) * GLYPH_SIZE)
                for x, y in contour
            ]})
    return curves


def _direction(word, arrow_left=False):
    width = _word_width(word)
    text_start = -width * .5
    curves = _word_curves(word, text_start)
    return {"label": word, "category": "Direction", "curves": curves}


